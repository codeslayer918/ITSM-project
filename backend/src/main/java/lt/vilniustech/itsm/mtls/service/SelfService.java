package lt.vilniustech.itsm.mtls.service;

import java.time.Instant;
import java.util.List;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import lt.vilniustech.itsm.mtls.auth.AuthContext;
import lt.vilniustech.itsm.mtls.domain.Account;
import lt.vilniustech.itsm.mtls.domain.IssuedCertificate;
import lt.vilniustech.itsm.mtls.pki.CsrValidator;
import lt.vilniustech.itsm.mtls.repo.AccountRepository;
import lt.vilniustech.itsm.mtls.repo.IssuedCertificateRepository;
import lt.vilniustech.itsm.mtls.web.ApiException;
import lt.vilniustech.itsm.mtls.web.dto.Dtos;

/** Operations of a logged-in user on their own account. */
@Service
public class SelfService {

    private final AccountRepository accounts;
    private final IssuedCertificateRepository certificates;
    private final CertificateService certificateService;
    private final BackupCodeService backupCodes;
    private final CsrValidator csrValidator;
    private final NotificationService notifications;
    private final AuditService audit;

    public SelfService(AccountRepository accounts, IssuedCertificateRepository certificates,
                       CertificateService certificateService, BackupCodeService backupCodes,
                       CsrValidator csrValidator, NotificationService notifications, AuditService audit) {
        this.accounts = accounts;
        this.certificates = certificates;
        this.certificateService = certificateService;
        this.backupCodes = backupCodes;
        this.csrValidator = csrValidator;
        this.notifications = notifications;
        this.audit = audit;
    }

    @Transactional(readOnly = true)
    public Dtos.MeView me(AuthContext auth, Instant sessionStartedAt) {
        Account account = account(auth);
        IssuedCertificate current = certificates.findByFingerprintSha256(auth.certFingerprint()).orElseThrow();
        return new Dtos.MeView(
                Dtos.AccountView.of(account,
                        certificates.countByAccountAndStatus(account, IssuedCertificate.Status.ACTIVE),
                        backupCodes.remaining(account)),
                current.getSerialHex(), current.getSubjectDn(), auth.admin(), sessionStartedAt);
    }

    @Transactional(readOnly = true)
    public List<Dtos.CertificateView> myCertificates(AuthContext auth) {
        return certificates.findByAccountOrderByCreatedAtDesc(account(auth)).stream()
                .map(c -> Dtos.CertificateView.of(c, false, auth.certSerial()))
                .toList();
    }

    /**
     * Backup method #1: a second certificate for another device (laptop + phone), the
     * equivalent of a second passkey. Requires an authenticated session, so only the
     * owner of an existing certificate can add one.
     */
    @Transactional
    public Dtos.IssuedResponse addDevice(AuthContext auth, Dtos.CsrRequest request) {
        Account account = account(auth);
        var key = csrValidator.validateAndExtractKey(request.csr());
        CertificateService.IssuedBundle bundle = certificateService.issue(account, key, request.label(),
                IssuedCertificate.IssuedVia.ADDITIONAL_DEVICE, auth.requestInfo());
        return new Dtos.IssuedResponse(bundle.record().getSerialHex(), bundle.record().getNotAfter(),
                bundle.record().getSubjectDn(), bundle.certificatePem(), bundle.chainPem(), null,
                "Certificate issued for the additional device.");
    }

    @Transactional
    public void revokeOwn(AuthContext auth, String serial) {
        Account account = account(auth);
        IssuedCertificate cert = java.util.Optional.ofNullable(lt.vilniustech.itsm.mtls.pki.PemUtils.normalizeSerial(serial))
                .flatMap(certificates::findBySerialHex)
                .filter(c -> c.getAccount().getId().equals(account.getId()))
                .orElseThrow(() -> ApiException.notFound("Unknown certificate."));
        certificateService.revoke(cert, IssuedCertificate.Reason.CESSATION_OF_OPERATION,
                "owner " + auth.username(), auth.requestInfo());
    }

    /** Backup method #2: 10 new one-time codes; the previous ones stop working. */
    @Transactional
    public Dtos.BackupCodesResponse regenerateBackupCodes(AuthContext auth) {
        Account account = account(auth);
        List<String> codes = backupCodes.regenerate(account);
        audit.record(AuditService.Type.BACKUP_CODES_GENERATED, AuditService.Outcome.SUCCESS, account.getUsername(),
                auth.requestInfo(), auth.certSerial(), "regenerated by the user");
        notifications.send(account.getEmail(), "Backup codes regenerated",
                "New backup codes were generated for '" + account.getUsername() + "'. The old codes no longer work.");
        return new Dtos.BackupCodesResponse(codes,
                "Store these codes offline. They are shown only once and can only be used to enrol a new certificate.");
    }

    private Account account(AuthContext auth) {
        return accounts.findById(auth.accountId()).orElseThrow(() -> ApiException.unauthorized("not_authenticated", "Unknown account."));
    }
}
